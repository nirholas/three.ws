// The winget manifests for ThreeWs.Agent (the standalone three-ws-agent.exe),
// as pure data. generate-manifests.mjs writes them to disk in the
// microsoft/winget-pkgs layout; tests/winget-manifests.test.js validates them
// against the vendored 1.28.0 JSON schemas.

import { stringify } from 'yaml';

export const MANIFEST_VERSION = '1.28.0';
export const PACKAGE_IDENTIFIER = 'ThreeWs.Agent';
export const DEFAULT_LOCALE = 'en-US';

/** winget-pkgs layout: manifests/<first letter>/<Publisher>/<Package>/<version>/. */
export function manifestDir(version) {
	const [publisher, name] = PACKAGE_IDENTIFIER.split('.');
	return `manifests/${publisher[0].toLowerCase()}/${publisher}/${name}/${version}`;
}

const SHORT_DESCRIPTION = 'Run a three.ws AI agent from your terminal, with local tools, saved sessions and the three.ws MCP tools.';

const DESCRIPTION = [
	'three-ws-agent runs a three.ws agent on your own machine. It opens a terminal UI with slash commands and streaming tool output, and gives the agent local file and shell tools inside a resource-limited sandbox, with an approval prompt before anything consequential runs.',
	'',
	'Sessions are saved locally in SQLite with full-text search and can be resumed or exported. Long goals can be split across parallel subagents, schedules are written in plain language ("every weekday at 9am") and run locally or on three.ws, and an optional gateway answers your own Telegram bot from the same machine.',
	'',
	'Sign in with `three-ws-agent login` to use the three.ws models and MCP tools, or point it at any OpenAI-compatible endpoint. This package is a single self-contained executable with Node.js built in, so nothing else needs to be installed.',
].join('\n');

const TAGS = ['ai', 'ai-agent', 'agent', 'cli', 'terminal', 'tui', 'mcp', 'model-context-protocol', 'automation', 'cron', 'subagents', 'sqlite', 'telegram', 'three-ws'];

/**
 * @param {object} o
 * @param {string} o.version
 * @param {string} o.releaseDate   YYYY-MM-DD
 * @param {Record<'x64'|'arm64', { url: string, sha256: string }>} o.installers
 * @returns {{ version: object, installer: object, defaultLocale: object }}
 */
export function wingetManifests({ version, releaseDate, installers }) {
	const base = { PackageIdentifier: PACKAGE_IDENTIFIER, PackageVersion: version };
	return {
		version: { ...base, DefaultLocale: DEFAULT_LOCALE, ManifestType: 'version', ManifestVersion: MANIFEST_VERSION },
		installer: {
			...base,
			// Node.js 26 supports Windows 10 1809 / Server 2019 and later.
			MinimumOSVersion: '10.0.17763.0',
			InstallerType: 'zip',
			NestedInstallerType: 'portable',
			NestedInstallerFiles: [{ RelativeFilePath: 'three-ws-agent.exe', PortableCommandAlias: 'three-ws-agent' }],
			Commands: ['three-ws-agent'],
			ReleaseDate: releaseDate,
			Installers: Object.entries(installers).map(([arch, a]) => ({
				Architecture: arch,
				InstallerUrl: a.url,
				InstallerSha256: a.sha256.toUpperCase(),
			})),
			ManifestType: 'installer',
			ManifestVersion: MANIFEST_VERSION,
		},
		defaultLocale: {
			...base,
			PackageLocale: DEFAULT_LOCALE,
			Publisher: 'three.ws',
			PublisherUrl: 'https://three.ws',
			PublisherSupportUrl: 'https://github.com/nirholas/three.ws/issues',
			PrivacyUrl: 'https://three.ws/legal/privacy',
			Author: 'three.ws',
			PackageName: 'three.ws Agent',
			PackageUrl: 'https://three.ws/docs/agent-cli',
			License: 'Apache-2.0',
			LicenseUrl: 'https://github.com/nirholas/three.ws/blob/main/packages/agent-cli/LICENSE',
			Copyright: 'Copyright three.ws',
			ShortDescription: SHORT_DESCRIPTION,
			Description: DESCRIPTION,
			Moniker: 'three-ws-agent',
			Tags: TAGS,
			ReleaseNotesUrl: 'https://three.ws/changelog',
			Documentations: [{ DocumentLabel: 'Agent CLI guide', DocumentUrl: 'https://three.ws/docs/agent-cli' }],
			ManifestType: 'defaultLocale',
			ManifestVersion: MANIFEST_VERSION,
		},
	};
}

const SCHEMA_URL = {
	version: `https://aka.ms/winget-manifest.version.${MANIFEST_VERSION}.schema.json`,
	installer: `https://aka.ms/winget-manifest.installer.${MANIFEST_VERSION}.schema.json`,
	defaultLocale: `https://aka.ms/winget-manifest.defaultLocale.${MANIFEST_VERSION}.schema.json`,
};

/** File name of each manifest, as winget-pkgs expects. */
export function manifestFileNames() {
	return {
		version: `${PACKAGE_IDENTIFIER}.yaml`,
		installer: `${PACKAGE_IDENTIFIER}.installer.yaml`,
		defaultLocale: `${PACKAGE_IDENTIFIER}.locale.${DEFAULT_LOCALE}.yaml`,
	};
}

/** Render one manifest as the YAML winget-pkgs accepts, with its schema hint. */
export function renderManifest(kind, data) {
	return [
		'# Generated by distributions/winget/scripts/generate-manifests.mjs from data/agent-cli-releases.json',
		`# yaml-language-server: $schema=${SCHEMA_URL[kind]}`,
		'',
		stringify(data, { lineWidth: 0 }).trimEnd(),
		'',
	].join('\n');
}
