"""Render fix_deps.py results (OUT_DIR/dep_fixes.json) as dependency-fixes.md.

Usage: python3 -I report_deps.py OUT_DIR
"""
import json, os, sys

D = sys.argv[1]
rows = sorted(json.load(open(os.path.join(D, "dep_fixes.json"))), key=lambda r: -(r.get("closed") or 0))


def steps(g):
    v = g.get("verify")
    if not v:
        return "-"
    b = g.get("baseline") or {}
    pre = {k for k, c in b.items() if c != 0}
    fixed_install = b.get("install", 0) != 0 and v.get("install") == 0
    return ("original lockfile could not install, this branch repairs it; " if fixed_install else "") + ", ".join(f"{k} {'ok' if c == 0 else 'failed before too' if k in pre else 'REGRESSED' if k in g.get('regressions', []) else 'failed'}" for k, c in v.items() if not (fixed_install and k == 'install')) + (f" ({g['note']})" if g.get("note") else "")


total_alerts = sum(r.get("alerts") or 0 for r in rows)
closed = sum(r.get("closed") or 0 for r in rows)
committed = [r for r in rows if r.get("commit")]
regressed = [r["repo"] for r in rows if any(g.get("regressions") for g in r.get("groups", []))]
out = [
    "# Dependency security fixes (prepared locally, not pushed)",
    "",
    "Generated by `report_deps.py` from a `fix_deps.py` run. These are the repos whose Dependabot",
    "security updates were failing with `conflicting-dependencies` (see `own-repos.md`).",
    "",
    "Method: every vulnerable package is moved to the highest patched release inside the major (or 0.minor)",
    "it is already locked to, first by refreshing it within its declared range, then with a scoped override",
    "(`npm overrides`, `pnpm.overrides`, yarn `resolutions`) or `cargo update`. An alert counts as open while",
    "any locked version sits in one of its advisory's vulnerable ranges. Install, build and tests run after the",
    "change; any failing step is rerun on the original lockfile, so a failure is only called a regression when",
    "the untouched repo passed. Packages with no patched release in their current major are left alone and",
    "listed, because fixing them means upgrading the parent that pins them.",
    "",
    f"**{closed} of {total_alerts} open alerts closed across {len(committed)} repos.** "
    + (f"Regressions to review before pushing: {', '.join(regressed)}." if regressed else "No build or test regressions."),
    "",
    "Ship: review a branch with `git -C /home/user/repo-fixes/<repo> show`, then the owner runs",
    "`GH_TOKEN=... docs/github-benchmark/push_fixes.sh --yes [repo ...]` to push the branches and open one PR each.",
    "",
    "| Repo | Alerts | Closed | Commit | Lockfiles (before -> after, checks) |",
    "|---|---|---|---|---|",
]
for r in rows:
    gs = "<br>".join(f'`{g["dir"]}` {g["kind"]}: {g.get("before")} -> {g.get("after")}, {steps(g)}' for g in r.get("groups", [])) or (r.get("error") or "-")
    out.append(f'| {r["repo"].split("/")[1]} | {r.get("alerts", "-")} | {r.get("closed") or 0} | {r.get("commit") or "-"} | {gs} |')

out += ["", "## Still open: needs a parent upgrade", ""]
for r in rows:
    left = sorted({u for g in r.get("groups", []) for u in g.get("unfixable", [])}) + r.get("unhandled", [])
    if left or r.get("manual"):
        out.append(f'**{r["repo"].split("/")[1]}**' + (f': {r["manual"]}' if r.get("manual") else ""))
        out += [f"- {u}" for u in left[:25]] + ([f"- and {len(left) - 25} more"] if len(left) > 25 else []) + [""]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "dependency-fixes.md"), "w").write("\n".join(out) + "\n")
print(f"closed {closed}/{total_alerts}, commits {len(committed)}, regressions {regressed}")
