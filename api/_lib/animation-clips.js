/** Whether `id` names a clip in the platform animation manifest. */
export function isValidClipId(id) {
	return typeof id === 'string' && CLIP_IDS.has(id);
}

/** Every clip id, in manifest order. */
export function listClipIds() {
	return [...CLIP_IDS];
}
