function buildSlots() {
	els.viewsGrid.innerHTML = '';
	slots.forEach((_, i) => {
		const slot = document.createElement('div');
		slot.className = 'view-slot';
		slot.dataset.index = String(i);
		slot.tabIndex = 0;
		slot.setAttribute('role', 'button');

		slot.innerHTML = `
			<div class="vs-empty">
				<span class="vs-icon" aria-hidden="true">＋</span>
				<span class="vs-label">${VIEW_LABELS[i]}</span>
			</div>
			<div class="vs-uploading">
				<div class="shimmer" aria-hidden="true"></div>
				<span>Uploading…</span>
			</div>
			<img loading="lazy" decoding="async" class="vs-thumb" alt="" />
			<div class="vs-preparing" aria-hidden="true">
				<span class="vs-preparing-text">Checking photo…</span>
				<span class="vs-preparing-bar" data-indeterminate="true"><i></i></span>
			</div>
			<span class="vs-badge">${VIEW_LABELS[i]}</span>
			<button type="button" class="vs-remove" aria-label="Remove ${VIEW_LABELS[i]} view">×</button>
			<div class="vs-error">
				<span class="vs-error-msg">Upload failed</span>
				<button type="button" class="vs-retry">Retry</button>
			</div>`;

		// Remove (stop click from also re-opening the picker).
		slot.querySelector('.vs-remove').addEventListener('click', (e) => {
			e.stopPropagation();
			clearSlot(i);
		});
		// Retry re-sends the same photo when the upload can succeed on a second
		// try; after a refusal (not a photo, too small) it opens the picker.
		slot.querySelector('.vs-retry').addEventListener('click', (e) => {
			e.stopPropagation();
			if (slots[i].retry) slots[i].retry();
			else openPicker(i);
		});

		// Click empty/error → browse for this slot (never a slot past the active
		// engine's cap, Pixal3D only reads the first four).
		slot.addEventListener('click', () => {
			if (slotEnabled(i) && (slots[i].state === 'empty' || slots[i].state === 'error')) openPicker(i);
		});
		slot.addEventListener('keydown', (e) => {
			if (e.key === 'Enter' || e.key === ' ') {
				e.preventDefault();
				if (slotEnabled(i) && (slots[i].state === 'empty' || slots[i].state === 'error')) openPicker(i);
				return;
			}
			if (slots[i].state !== 'uploaded') return;
			// Reorder and remove without a pointer: Alt+Arrow moves the photo one
			// place (the first place is the one a single-image engine reads), and
			// Delete removes it. Focus follows the photo.
			const step = { ArrowLeft: -1, ArrowUp: -1, ArrowRight: 1, ArrowDown: 1 }[e.key];
			if (e.altKey && step) {
				e.preventDefault();
				const to = i + step;
				if (to < 0 || !slotEnabled(to) || slots[to].state === 'preparing') return;
				swapSlots(i, to);
				slotEl(to)?.focus();
			} else if (e.key === 'Delete' || e.key === 'Backspace') {
				e.preventDefault();
				clearSlot(i);
			}
		});

		// Drag to reorder (uploaded slots only).
		slot.addEventListener('dragstart', (e) => {
			if (slots[i].state !== 'uploaded') {
				e.preventDefault();
				return;
			}
			e.dataTransfer.setData('application/x-forge-slot', String(i));
			e.dataTransfer.effectAllowed = 'move';
			slot.classList.add('dragging');
		});
		slot.addEventListener('dragend', () => slot.classList.remove('dragging'));

		// Drop target — accepts files OR a dragged thumbnail (reorder).
		slot.addEventListener('dragover', (e) => {
			e.preventDefault();
			e.dataTransfer.dropEffect = e.dataTransfer.types.includes('application/x-forge-slot')
				? 'move'
				: 'copy';
			slot.classList.add('drop-target');
		});
		slot.addEventListener('dragleave', () => slot.classList.remove('drop-target'));
		slot.addEventListener('drop', (e) => {
			e.preventDefault();
			slot.classList.remove('drop-target');
			if (!slotEnabled(i)) return;
			const from = e.dataTransfer.getData('application/x-forge-slot');
			if (from !== '') {
				swapSlots(Number(from), i);
			} else if (e.dataTransfer.files?.length) {
				handleFiles(i, e.dataTransfer.files);
			}
		});

		els.viewsGrid.appendChild(slot);
		renderSlot(i);
	});
}

