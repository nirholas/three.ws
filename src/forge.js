function showError(message, { allowOverride = false, title = 'Generation failed' } = {}) {
	stopElapsed();
	// Freeze the timeline where it really got to and drop the warming card: the
	// job is over, so nothing may keep implying work is still happening.
	timeline.fail();
	stopRateLimitCountdown();
	if (els.errorTitle) els.errorTitle.textContent = title;
	els.errorMessage.classList.remove('upload-sign-in', 'upload-sign-in--panel');
	els.errorMessage.textContent = message;
	// Revealing the panel by class is not reliably announced; this is.
	announceForgeError(title, message);
	// The "Generate anyway" affordance only exists for the vision pre-check
	// rejection; every other error hides it so it can't leak across states.
	if (els.generateAnyway) els.generateAnyway.classList.toggle('is-hidden', !allowOverride);
	// The local-refine escape hatch belongs only to the rate-limit state.
	if (els.refineLocally) els.refineLocally.classList.add('is-hidden');
	// Lane-switch buttons belong only to the lane-failed state (showLaneFailed
	// re-reveals them after this reset).
	if (els.errorLanes) {
		els.errorLanes.classList.add('is-hidden');
		els.errorLanes.innerHTML = '';
		// showStorageDown relabels this group for its own contents; every other
		// state that reveals it fills it with engine switches, so reset the name.
		els.errorLanes.setAttribute('aria-label', 'Retry on another engine');
	}
	if (els.retry) els.retry.disabled = false;
	showState('error');
	// A failure the user cannot see is a hang. On a stacked layout the stage sits
	// below the fold, so bring it up before moving focus into it.
	revealStage();
	// The async flow just landed on an error: put keyboard focus on the primary
	// recovery action, unless the user is already typing somewhere else.
	const ax = document.activeElement;
	if (els.retry && (!ax || ax === document.body || ax === els.generate)) {
		els.retry.focus({ preventScroll: true });
	}
}

