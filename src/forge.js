function isModlyEngine(id) {
	return typeof id === 'string' && id.startsWith('modly:');
}

function modlyEngineLabel(id) {
	const modelId = id.slice('modly:'.length);
	return `Your GPU (${modly?.modelById(modelId)?.name || modelId})`;
}

