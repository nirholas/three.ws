// Poster capture — the visual half of every creation card. Image-intermediate
// engines store their flux reference image as the preview, but geometry-first
// and sketch lanes paint no image at all, so their gallery/showcase cards used
// to render as glyph placeholders. Once the finished mesh is standing in the
// viewer, render it onto a small studio-backdrop canvas and attach it to the
// creation row (POST /api/forge-poster — fill-only, owner-scoped, best-effort).
const POSTER_MAX_DIM = 640;
const postedPosters = new Set();

function renderPosterFrame(sourceDataUrl) {
	return new Promise((resolve) => {
		const img = new Image();
		img.onload = () => {
			const scale = Math.min(1, POSTER_MAX_DIM / Math.max(img.width, img.height, 1));
			const w = Math.max(1, Math.round(img.width * scale));
			const h = Math.max(1, Math.round(img.height * scale));
			const canvas = document.createElement('canvas');
			canvas.width = w;
			canvas.height = h;
			const ctx = canvas.getContext('2d');
			if (!ctx) return resolve(null);
			// Same studio backdrop as the live viewer, so mesh posters read as a
			// consistent set next to flux reference images in the galleries.
			const backdrop = ctx.createRadialGradient(w / 2, 0, 0, w / 2, 0, Math.max(w, h) * 1.2);
			backdrop.addColorStop(0, '#1a1612');
			backdrop.addColorStop(0.7, '#0b0a09');
			backdrop.addColorStop(1, '#0b0a09');
			ctx.fillStyle = backdrop;
			ctx.fillRect(0, 0, w, h);
			ctx.drawImage(img, 0, 0, w, h);
			const webp = canvas.toDataURL('image/webp', 0.85);
			// Browsers without webp encoding silently hand back PNG — send what we got.
			resolve(webp.startsWith('data:image/webp') ? webp : canvas.toDataURL('image/png'));
		};
		img.onerror = () => resolve(null);
		img.src = sourceDataUrl;
	});
}

async function capturePoster(creationId) {
	if (!creationId || postedPosters.has(creationId) || !els.viewer?.toDataURL) return;
	postedPosters.add(creationId);
	try {
		if (!els.viewer.loaded) {
			await new Promise((resolve) =>
				els.viewer.addEventListener('load', resolve, { once: true }),
			);
		}
		// Let the materialize entrance settle so the capture is a steady frame.
		await sleep(REDUCED_MOTION ? 300 : 1500);
		// A newer generation or an opened creation replaced the model — skip.
		if (currentCreationId !== creationId) return;
		const frame = await renderPosterFrame(els.viewer.toDataURL('image/png'));
		if (!frame) return;
		const res = await fetch('/api/forge-poster', {
			method: 'POST',
			headers: { 'content-type': 'application/json', ...CLIENT_HEADERS },
			body: JSON.stringify({ creation_id: creationId, image: frame }),
		});
		const data = await res.json().catch(() => ({}));
		// The card for this creation is already on screen with a placeholder —
		// refresh the strip so the new poster shows without a reload.
		if (data?.stored) loadGallery();
	} catch {
		// Best-effort: a missed poster never disturbs the result flow.
	}
}

// Render the provenance badge from job metadata: how the mesh was produced
// (engine + tier + path) plus any multi-view conditioning. Shows whatever is
// known — the geometry-first path has no reference views, the image path does.
function setViewsBadge(meta) {
	if (!els.resultViews) return;
	const parts = [];
	const used = Number(meta?.views_used);
	if (Number.isFinite(used) && used >= 1) {
		parts.push(`${used} ${used === 1 ? 'view' : 'views'}`);
		if (meta.multiview) parts.push('multi-view');
	}
	if (meta?.backend) parts.push(engineLabel(meta.backend));
	if (meta?.tier) parts.push(meta.tier);
	if (meta?.path === 'geometry') parts.push('geometry-first');
	if (meta?.path === 'sketch') parts.push('sketch→3D');
	if (meta?.rigged) parts.push('already rigged');
	if (parts.length === 0) {
		els.resultViews.classList.add('is-hidden');
		els.resultViews.textContent = '';
		return;
	}
	els.resultViews.textContent = parts.join(' · ');
	els.resultViews.classList.remove('is-hidden');
}

// Surface the automated quality signal the server attached to this generation.
// Two sources, in order of confidence:
//   • quality_gate: the vision-QA verdict (semantic: does it look like the
//     prompt). A pass with a numeric score reads "Verified NN%"; a fail that
//     nonetheless shipped (best-of retry kept the top roll) reads a low-band
//     warning so the user knows to regenerate.
//   • quality: the fast deterministic scorer (structural). Used only when no
//     vision verdict exists (the trusted fast-lane path), shown as a quiet
//     "Checked" so a good draft still gets a confidence cue without a score.
// Anything unscored (QA unavailable / older gallery model) shows nothing rather
// than a fabricated number.
function setQualityBadge(meta) {
	const el = els.resultQuality;
	if (!el) return;
	const hide = () => {
		el.classList.add('is-hidden');
		el.removeAttribute('data-band');
		el.textContent = '';
		el.title = 'Automated quality check';
	};
	setQualityRetryChip(meta?.quality_retry);
	const gate = meta?.quality_gate;
	// A real vision verdict: qa_available and a numeric score.
	if (gate && gate.qa_available !== false && Number.isFinite(Number(gate.score))) {
		const score = Math.round(Number(gate.score));
		if (gate.pass === true) {
			el.dataset.band = 'verified';
			el.textContent = `Verified ${score}%`;
			el.title = gate.reason ? `Quality check passed: ${gate.reason}` : 'Passed the automated quality check';
		} else {
			el.dataset.band = 'low';
			el.textContent = `Low ${score}%`;
			el.title = gate.reason
				? `Below the quality bar: ${gate.reason}. Try Regenerate.`
				: 'Below the automated quality bar: try Regenerate.';
		}
		el.classList.remove('is-hidden');
		return;
	}
	// No vision verdict: fall back to the fast structural scorer if it vouched.
	const q = meta?.quality;
	if (q && q.flag === 'ok') {
		el.removeAttribute('data-band');
		el.textContent = 'Checked';
		el.title = 'Passed the fast quality check';
		el.classList.remove('is-hidden');
		return;
	}
	hide();
}

// What the automatic quality retry did for this model (quality_retry on a done
// response from the synchronous lanes). The server writes the full sentence;
// the chip shows a short label and carries that sentence as its accessible name
// and tooltip, so a regenerated or kept-first model is never shown silently.
const QUALITY_RETRY_LABELS = {
	retry: 'Regenerated once',
	first: 'Kept first of two',
	busy: 'Not regenerated',
	allowance: 'Not regenerated',
	retry_failed: 'Retry did not finish',
};
function setQualityRetryChip(retry) {
	const el = els.resultQualityRetry;
	if (!el) return;
	const key = retry?.ran ? retry.kept : retry?.declined;
	const label = key ? QUALITY_RETRY_LABELS[key] : null;
	const message = typeof retry?.message === 'string' ? retry.message : '';
	if (!label || !message) {
		el.classList.add('is-hidden');
		el.removeAttribute('data-kind');
		el.removeAttribute('aria-label');
		el.textContent = '';
		el.title = '';
		return;
	}
	el.dataset.kind = retry.ran ? 'ran' : 'declined';
	el.textContent = label;
	el.title = message;
	el.setAttribute('aria-label', `${label}. ${message}`);
	el.classList.remove('is-hidden');
}

// Materialize entrance — conceal the standing viewer, play the WebGL dissolve
// reveal over it (src/forge-reveal.js), then crossfade back and hand the
// final camera angle to model-viewer so the turntable continues seamlessly.
// Presentation only: any failure restores the viewer immediately.
let revealSeq = 0;
async function playMaterialize(glbUrl) {
	if (REDUCED_MOTION || !els.viewerShell) return;
	const seq = ++revealSeq;
	els.viewer.style.opacity = '0';
	try {
		const { playForgeReveal } = await import('./forge-reveal.js');
		const viewerLoaded = new Promise((resolve) => {
			if (els.viewer.loaded) return resolve();
			els.viewer.addEventListener('load', resolve, { once: true });
		});
		const end = await playForgeReveal({
			container: els.viewerShell,
			glbUrl,
			waitFor: viewerLoaded,
		});
		if (seq === revealSeq && end && Number.isFinite(end.azimuthDeg)) {
			els.viewer.cameraOrbit = `${end.azimuthDeg.toFixed(1)}deg ${end.polarDeg.toFixed(1)}deg auto`;
		}
	} catch {
		// The standing viewer is the fallback — nothing to surface.
	} finally {
		if (seq === revealSeq) els.viewer.style.opacity = '1';
	}
}

// Show "Refine → <next tier>" only when a higher tier exists and the current
