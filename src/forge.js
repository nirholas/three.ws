// The honest price for the current engine + tier, as a styled segment. The web
// gate charges only High tier (hold $THREE or pay per generation); Draft and
// Standard run free on the platform's rate-limited lanes; BYOK engines bill the
// caller's own provider key. `_highAccess.eligible` reflects a resolved $THREE
// hold, so a holder sees High as already unlocked.
function costSegment(backend, tierMeta) {
	const houseLane = backend.house_key_available && !providerKey;
	if (backend.byok && !houseLane) return 'billed to your own key';
	if (tierMeta.id === 'high') {
		return _highAccess?.eligible
			? '<span class="est-free">Free</span> · you hold $THREE'
			: `<span class="est-cost">$${tierMeta.price_usdc}</span> or hold $THREE`;
	}
	return '<span class="est-free">Free</span>';
}

// Render the honest time/cost/poly estimate for the current engine + tier from
// the catalog. No fabricated numbers — everything comes from /api/forge?catalog.
function updateEstimate() {
	if (!els.estimate) return;
	if (selectedEngine.modly) {
		renderModlyEstimate();
		return;
	}
	if (!catalog) return;
	const backend = catalog.backends.find((b) => b.id === selectedEngine.backend);
	const tierMeta = catalog.tiers.find((t) => t.id === selectedTier);
	if (!backend || !tierMeta) {
		els.estimate.textContent = '';
		return;
	}
	const est = (backend.estimates?.[selectedEngine.path] || []).find(
		(e) => e.tier === selectedTier,
	);
	// Holder-readable, not pipeline-internal: say how long it usually takes and
	// what the engine does, in plain words — and stay honest to the active tab.
	// On the "Describe it" (text) tab the image-path engines synthesize a preview
	// from the prompt first, so "builds from a reference image" would be wrong —
	// the user supplied no image. Only the photos tab builds from a real reference.
	const parts = [`<strong>${tierMeta.label}</strong>`, costSegment(backend, tierMeta)];
	const lane = backend.id === 'pixal3d' ? backend.health : null;
	if (lane?.gated) {
		parts.push(lane.reason);
	} else if (lane?.typical_seconds) {
		// Measured, not hoped for: the median of recent finished jobs, and the point
		// where the job moves to the standard engine so the wait has a ceiling.
		const typicalMin = Math.max(1, Math.round(lane.typical_seconds / 60));
		const capMin = Math.round(lane.allowance_seconds / 60);
		parts.push(`recent runs took ~${typicalMin} min; after ${capMin} min it finishes on the standard engine`);
	} else if (est?.eta_seconds) {
		// Measured p50 and p95 of the lane's finished jobs when it has enough
		// history, the catalog figure worded as an estimate when it does not.
		const range = describeRange({
			timing: laneTimings.timing(selectedEngine.backend),
			catalogEtaS: est.eta_seconds,
		});
		if (range) parts.push(range);
		if (lane) parts.push(`after ${Math.round(lane.allowance_seconds / 60)} min it finishes on the standard engine`);
	}
	// Credits are a real charge only on metered lanes (BYOK or the paid High tier).
	// Never tack a credit figure onto a "Free" line — "Free · ~3 credits" reads as
	// a contradiction. costSegment() owns the cost word; this stays consistent with it.
	if (est?.credits != null && (backend.byok || tierMeta.id === 'high'))
		parts.push(`~${est.credits} credits`);
	if (backend.poly_control) parts.push(`up to ${tierMeta.polycount.toLocaleString()} polygons`);
	if (selectedEngine.path === 'geometry') parts.push('shapes geometry straight from the prompt');
	else if (selectedEngine.path === 'sketch') parts.push('untextured geometry from your sketch');
	else if (mode === 'image') parts.push('builds from your reference photos');
	else parts.push('renders a preview image, then builds 3D');
	els.estimate.innerHTML = parts.join(' · ');
	updateTierTitles();
	renderQuote(els.quote, {
		tier: selectedTier,
		path: selectedEngine.path,
		backend: selectedEngine.backend,
		images: mode === 'image',
		headers: CLIENT_HEADERS,
	});
}

// Stamp each tier button's tooltip with the catalog's real blurb, the typical
// time on the currently selected engine, and the polygon budget, so the
// quality/time tradeoff is legible before a tier is ever selected. The static
// HTML titles remain as the pre-catalog fallback.
function updateTierTitles() {
	if (!els.tier || !catalog) return;
	const backend = catalog.backends?.find((b) => b.id === selectedEngine.backend);
	for (const btn of els.tier.querySelectorAll('button[data-tier]')) {
		const t = catalog.tiers?.find((x) => x.id === btn.dataset.tier);
		if (!t) continue;
		const est = (backend?.estimates?.[selectedEngine.path] || []).find((e) => e.tier === t.id);
		const parts = [t.blurb];
		const range = est?.eta_seconds
			? describeRange({ timing: laneTimings.timing(backend.id), catalogEtaS: est.eta_seconds })
			: '';
		if (range) parts.push(`${range} on ${backend.label}`);
		if (Number(t.polycount) > 0) parts.push(`up to ${t.polycount.toLocaleString()} polygons`);
		btn.title = `${t.label}: ${parts.filter(Boolean).join(' · ')}`;
	}
}

