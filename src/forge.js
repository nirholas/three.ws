// The High tier is a $THREE holder perk (gated server-side). When the user picks
// it, surface their access up front — a frosted lock with a Get $THREE path for
// non-holders (and the Generate button disabled for High), an "Unlocked" ribbon
// for holders (pass primed so their request clears the gate without a round-trip
// stall). Draft and Standard clear the lock (they're free, never gated). Degrades
// safely: if the access read fails we show a retry but DON'T trap the user — the
// server stays the final authority and a 403 falls back to the upsell modal.
let _accessHost = null;
let highLocked = false; // true → High is selected but the holder isn't eligible
let _highAccess = null; // last resolved forge.high access payload (for the gate modal)

// The only combination the server actually $THREE-gates: High tier on a PLATFORM-keyed
// backend. BYOK engines run on the caller's own vendor key, so the server exempts BYOK
// High (key-gated, not hold-gated), and so must the client, or a non-holder with their
// own Meshy/Tripo/Rodin key would be wrongly blocked from High. The one exception is a
// house-key lane (Tripo, when TRIPO_API_KEY is set): the server bills that the same as
// any other platform lane even though the backend is flagged `byok`, because the key
// running the job is ours, not the caller's, so the client gate must match (a caller
// who typed their own key still stays exempt; see updateByokRow's providerKey check
// below). Draft/Standard are never gated. Every client gate check keys on this.
function highTierNeedsPass() {
	if (selectedTier !== 'high' || selectedEngine.modly) return false;
	if (!selectedEngine.byok) return true;
	return Boolean(selectedEngine.houseKeyAvailable) && !providerKey;
}

function accessHost() {
	if (_accessHost || !els.tier) return _accessHost;
	const host = document.createElement('div');
	host.className = 'fq-access';
	host.hidden = true;
	(els.estimate || els.tier).insertAdjacentElement('afterend', host);
	_accessHost = host;
	return host;
}

// Reflect the High-tier gate onto the Generate button: disabled + relabelled
// while High is selected and the user is ineligible. Only touches the button when
// not mid-job (setBusy owns the busy label).
function applyHighGate() {
	if (!els.generate || els.generate.dataset.busy === '1') return;
	const locked = highTierNeedsPass() && highLocked;
	els.generate.disabled = locked;
	els.generate.classList.toggle('is-gated', locked);
	if (els.generateLabel) {
		els.generateLabel.textContent = locked ? 'Hold $THREE for High' : 'Generate';
	}
}

async function reflectHighAccess(tierId, { silent = false } = {}) {
	const host = accessHost();
	if (!host) return;
	if (tierId !== 'high') {
		highLocked = false;
		_highAccess = null;
		renderLock(host, { clear: true });
		// High isn't selected — let the persistent hint advertise it again.
		if (els.holderNote) els.holderNote.hidden = false;
		applyHighGate();
		return;
	}
	// High on a BYOK engine is server-exempt (the caller's own vendor key pays), so it's
	// never $THREE-gated here either: clear any lock, drop the holder note, and let the
	// BYOK key flow take over. This is the path that keeps BYOK High byte-for-byte free.
	if (!highTierNeedsPass()) {
		highLocked = false;
		renderLock(host, { clear: true });
		if (els.holderNote) els.holderNote.hidden = true;
		applyHighGate();
		return;
	}
	// Platform-keyed High — the real $THREE gate. The in-place lock panel takes over, so
	// the small persistent hint stands down to avoid stacking two "holder feature" notes.
	if (els.holderNote) els.holderNote.hidden = true;
	// Re-evaluating after an engine switch (silent) reuses the last resolved verdict so
	// the panel doesn't flash a loading state for a check we already made.
	let access = silent && _highAccess ? _highAccess : null;
	if (!access) {
		renderLock(host, { loading: true });
		const data = await getAccess('forge.high');
		// User moved off High, or switched to a BYOK engine, while we fetched.
		if (!highTierNeedsPass()) return;
		access = data?.access || null;
	}
	if (!access) {
		// Access read failed — show a retry, but don't lock (fail open; the server
		// enforces and a real holder isn't trapped behind a transient hiccup).
		_highAccess = null;
		highLocked = false;
		renderLock(host, { error: true, onRetry: () => reflectHighAccess('high') });
		applyHighGate();
		return;
	}
	_highAccess = access;
	highLocked = !access.eligible;
	renderLock(
		host,
		lockStateFromAccess(access, {
			getThreeUrl: '/three',
			onUseFree: () => selectTier('standard'),
			useFreeLabel: 'Use Standard (free)',
			// Working Pay-per-use CTA: pay $THREE for one High generation in place.
			onPayPerUse: (pay) => payThenGenerate(pay),
		}),
	);
	applyHighGate();
	// Keep the persistent button pill + note in sync with the fresh verdict.
	applyHighAffordances(access);
	// Reflect the resolved hold in the cost line too — High flips to "Free" for a
	// holder without a reload.
	updateEstimate();
	if (access.eligible) primeTierPass();
}

