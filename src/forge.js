// Resume an in-flight generation persisted before a reload/navigation. The
// server holds all job state, so picking it back up is just polling the same
// job id; the panel restores in its mesh phase with an honest elapsed count.
async function resumeInflight({ note } = {}) {
	const inflight = readInflight();
	if (!inflight) return false;
	const gateToken = runGate.enter();
	if (!gateToken) return false;
	const path = inflight.path || inflight.body?.path || null;
	const backend = inflight.backend || inflight.body?.backend || null;

	pollAbort = false;
	currentCreationId = inflight.creationId || null;
	setBusy(true);
	// Restore the timeline in its mesh phase: the earlier stages provably
	// finished (the job exists, and the reference view was recorded with it), and
	// the next real poll refines the rest. A resumed job whose reference view was
	// never captured locally still gets it: the poll response carries it.
	timeline.resume({
		mode: path === 'sketch' ? 'sketch' : 'text',
		backend,
		referenceUrl: inflight.previewImageUrl || null,
		elapsedS: Math.max(0, Math.round((Date.now() - inflight.startedAt) / 1000)),
	});
	setLaneNote(note || 'Welcome back. This generation kept running while you were away.');
	startElapsed({ waitedS: (Date.now() - inflight.startedAt) / 1000, onLane: Boolean(inflight.jobId) });
	showState('generating');

	const pollStats = { resumed: true };
	try {
		// Left before the POST answered: resend the recorded request under its
		// recorded key. The server answers with the job that request started (or
		// starts it, if the first send never arrived), never with a second job.
		let jobId = inflight.jobId;
		let done = null;
		if (!jobId) {
			const job = await startResumedJob(inflight);
			if (!job || pollAbort) return true;
			waitClock.accepted();
			rememberFromResponse(job);
			if (job.creation_id) currentCreationId = job.creation_id;
			if (job.status === 'done' && job.glb_url) {
				done = job;
				pollStats.finishedAway = true;
			} else {
				saveInflight(job, inflight.label);
				jobId = job.job_id;
			}
		}
		if (!done) done = await pollUntilDone(jobId, pollStats);
		if (pollAbort || !done) return true;
		clearInflight();
		rememberFromResponse(done);
		if (done.creation_id) currentCreationId = done.creation_id;
		timeline.finalizing();
		markProgressDone();
		// No directed-prompt reveal on a resumed job: the submit response is long
		// gone and the rewrite is not persisted with the creation, so showResult's
		// own reset leaves the panel hidden rather than showing a stale prompt.
		showResult(
			done.glb_url,
			inflight.label || 'Forged model',
			{
				views_used: done.views_used,
				multiview: done.multiview,
				backend: done.backend ?? backend,
				tier: done.tier ?? inflight.tier ?? inflight.body?.tier,
				path: done.path ?? path,
				quality: done.quality,
				quality_gate: done.quality_gate,
				quality_retry: done.quality_retry,
				rigged: done.rigged,
			},
			{ autoSaved: !!done.creation_id },
		);
		showFinishedAway(pollStats.finishedAway);
		timeline.complete();
		loadGallery();
		if (!done.preview_image_url && !inflight.previewImageUrl) {
			capturePoster(currentCreationId);
		}
	} catch (err) {
		if (pollAbort) return true;
		// A job that may still be alive keeps its record for the next visit.
		if (!keepsInflight(err)) clearInflight();
		timeline.fail();
		stopElapsed();
		const failure = forgeErrorDescriptor(err, 'generation_failed');
		showError(failure.message, { title: failure.title });
	} finally {
		if (runGate.leave(gateToken)) setBusy(false);
	}
	return true;
}

// Gather + validate the active mode's composer inputs into a run cfg, or null
// when something's missing (focusing/flagging the offending field as a side
// effect, exactly as submit always has). Shared by the Generate button and the
// pay-per-use path so both build the job identically.
function collectComposerCfg() {
	if (mode === 'text') {
		const prompt = els.prompt.value.trim();
		if (prompt.length < 3) {
			els.prompt.focus();
			return null;
		}
		return { prompt, imageUrls: [] };
	}

	// Sketch mode — one drawing + a required prompt naming what it depicts.
	if (mode === 'sketch') {
		if (sketch.state === 'uploading') {
			els.generateLabel.textContent = 'Waiting for upload…';
			setTimeout(() => {
				if (!els.generate.disabled) els.generateLabel.textContent = 'Generate';
			}, 1600);
			return null;
		}
		if (sketch.state !== 'uploaded' || !sketch.url) {
			const slot = sketchSlotEl();
			slot?.focus();
			slot?.classList.add('drop-target');
			setTimeout(() => slot?.classList.remove('drop-target'), 600);
			return null;
		}
		const prompt = els.sketchPrompt.value.trim();
		if (prompt.length < 3) {
			// Make the required-input contract unmissable: flag the field and tint
			// the "Required" tag until the user types a description.
			els.sketchPrompt.setAttribute('aria-invalid', 'true');
			if (els.sketchReqTag) els.sketchReqTag.dataset.missing = 'true';
			els.sketchPrompt.focus();
			return null;
		}
		return { prompt, imageUrls: [sketch.url] };
	}

	// Image / multi-view mode.
	if (slots.some((s) => s.state === 'uploading' || s.state === 'preparing')) {
		els.generateLabel.textContent = 'Waiting for uploads…';
		setTimeout(() => {
			if (!els.generate.disabled) els.generateLabel.textContent = 'Generate';
		}, 1600);
		return null;
	}
	const urls = uploadedUrls();
	if (urls.length === 0) {
		const first = slotEl(0);
		first?.focus();
		first?.classList.add('drop-target');
		setTimeout(() => first?.classList.remove('drop-target'), 600);
		return null;
	}
	return { prompt: els.imagePrompt.value.trim(), imageUrls: urls };
}

function submit() {
	// Your GPU lane: the run happens in Modly on this computer, not /api/forge.
	if (selectedEngine.modly && mode === 'image') {
		runModly(selectedEngine.modelId);
		return;
	}
	// Platform-keyed High is a $THREE holder perk. The Generate button is disabled
	// when locked, but a keyboard submit (⌘↵) can still reach here — open the upsell
	// (with the working Pay-per-use path) instead of firing a request the server will
	// gate. BYOK High is exempt, so highTierNeedsPass() lets it through untouched.
	if (highTierNeedsPass() && highLocked) {
		if (_highAccess) onGate(_highAccess, gateOpts());
		else reflectHighAccess('high');
		return;
	}
	const cfg = collectComposerCfg();
	// A fresh user-initiated generation resets the automatic lane-hop budget —
	// the single silent hop belongs to one submission, never accumulates.
	autoLaneHops = 0;
	throttlePanel.resetAutoRetry();
	if (!cfg) return;
	const seed = seedField.seedForSubmit(mintSeed);
	if (seed !== null) run({ ...cfg, seed });
}

// Options handed to the gate modal / in-place lock so their "Pay per generation"
// CTA actually works: pay $THREE for one High generation, then run the current
// composer inputs with the settled proof attached.
function gateOpts() {
	return { onPayPerUse: (pay) => payThenGenerate(pay) };
}

// The consumption lever, end to end: price comes from the gate's pay_per_use (or
// the resolved access), the user pays $THREE through the designed modal, and the
// generation re-fires immediately with { paymentId, refId } so the server's gate
// is satisfied per use. No-op if the composer inputs are incomplete (the field is
// focused) or the user cancels the payment.
async function payThenGenerate(pay) {
	const usd = Number(pay?.usd) || Number(_highAccess?.pay_per_use?.usd) || 0;
	if (!(usd > 0)) return;
	const cfg = collectComposerCfg();
	if (!cfg) return;
	const seed = seedField.seedForSubmit(mintSeed);
	if (seed === null) return;
	// Ensure the job runs at High (the tier the payment buys) even if the click
	// came from the in-place lock before any submit.
	if (selectedTier !== 'high') selectTier('high');
	const result = await payForHighGeneration({ usd });
	if (!result?.ok) return; // cancelled or failed — the modal explained why
	run({ ...cfg, seed, payment: { paymentId: result.paymentId, refId: result.refId, reused: Boolean(result.reused), usd } });
}

