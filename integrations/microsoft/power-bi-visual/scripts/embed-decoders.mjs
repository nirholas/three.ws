// Embeds the glTF build of the Draco decoder that ships with the pinned three.js
// version into a TypeScript module, so the visual never fetches a decoder from a
// CDN. The glTF build decodes everything KHR_draco_mesh_compression allows and
// is about a third smaller than the general build.
//
// Power BI only lets a visual reach the hosts listed in its WebAccess privilege
// (https://three.ws for this visual), and pbiviz's webpack config has no raw or
// binary asset loader. Generating a module from node_modules keeps the decoder
// byte-identical to the three.js release in package-lock.json, and the output is
// regenerated before every build, test and package run (src/generated is
// gitignored).
//
// The meshopt decoder needs no step like this: three.js ships it as an ES module
// with its WebAssembly inlined.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'package.json'));
// three's exports map hides package.json, so walk up from its main entry.
const threeDir = join(dirname(require.resolve('three')), '..');
const dracoDir = join(threeDir, 'examples', 'jsm', 'libs', 'draco', 'gltf');
const threeVersion = JSON.parse(readFileSync(join(threeDir, 'package.json'), 'utf8')).version;

const wrapper = readFileSync(join(dracoDir, 'draco_wasm_wrapper.js'), 'utf8');
const wasm = readFileSync(join(dracoDir, 'draco_decoder.wasm'));

const out = join(root, 'src', 'generated', 'dracoDecoder.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
	out,
	[
		`// Generated by scripts/embed-decoders.mjs from three@${threeVersion}. Do not edit.`,
		`export const DRACO_THREE_VERSION: string = ${JSON.stringify(threeVersion)};`,
		`export const DRACO_WASM_WRAPPER_JS: string = ${JSON.stringify(wrapper)};`,
		`export const DRACO_DECODER_WASM_BASE64: string = ${JSON.stringify(wasm.toString('base64'))};`,
		'',
	].join('\n'),
);
console.log(`[embed-decoders] three@${threeVersion}: wrapper ${wrapper.length} B, wasm ${wasm.length} B -> ${out}`);
