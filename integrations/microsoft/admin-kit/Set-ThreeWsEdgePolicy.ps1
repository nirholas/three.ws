<#
.SYNOPSIS
Sets the three.ws Edge policies: installs the web app, and the extensions that are on Edge Add-ons.

.DESCRIPTION
Generated by scripts/microsoft-admin-kit.mjs. Do not edit by hand. It merges with the
policies already on the machine (it never replaces another entry) and -Remove takes out
only what this script added. Use -WhatIf to see every change without making it.
Run from an elevated prompt for -Scope Machine. Prefer Intune or Group Policy for fleets;
this script is for pilots, scripted images and non-managed devices.

.PARAMETER Scope
Machine writes HKLM (all users, needs elevation). User writes HKCU (the current user only).

.PARAMETER Remove
Rolls the policies back.

.EXAMPLE
./Set-ThreeWsEdgePolicy.ps1 -WhatIf

.EXAMPLE
./Set-ThreeWsEdgePolicy.ps1 -Scope Machine -Remove
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [ValidateSet('Machine', 'User')]
    [string]$Scope = 'Machine',
    [switch]$Remove
)

$ErrorActionPreference = 'Stop'
$hive = if ($Scope -eq 'Machine') { 'HKLM:' } else { 'HKCU:' }
$edgeKey = Join-Path $hive 'SOFTWARE\Policies\Microsoft\Edge'
$extKey = Join-Path $edgeKey 'ExtensionInstallForcelist'

$webApps = @'
[{"url":"https://three.ws/?source=pwa","launch_container":"window","create_desktop_shortcut":true,"fallback_app_name":"three.ws"}]
'@ | ConvertFrom-Json
$extensions = @()

function Set-WebAppPolicy {
    [CmdletBinding(SupportsShouldProcess)]
    param([switch]$Remove)
    $current = @()
    if (Test-Path $edgeKey) {
        $raw = (Get-ItemProperty -Path $edgeKey -Name WebAppInstallForceList -ErrorAction SilentlyContinue).WebAppInstallForceList
        if ($raw) { $current = @($raw | ConvertFrom-Json) }
    }
    $ours = @($webApps.url)
    $kept = @($current | Where-Object { $ours -notcontains $_.url })
    $next = if ($Remove) { $kept } else { @($kept) + @($webApps) }
    if ($PSCmdlet.ShouldProcess("$edgeKey\WebAppInstallForceList", $(if ($Remove) { 'Remove three.ws web app' } else { 'Add three.ws web app' }))) {
        if (-not (Test-Path $edgeKey)) { New-Item -Path $edgeKey -Force | Out-Null }
        if ($next.Count -eq 0) {
            Remove-ItemProperty -Path $edgeKey -Name WebAppInstallForceList -ErrorAction SilentlyContinue
        } else {
            $json = ConvertTo-Json -InputObject @($next) -Compress -Depth 5
            Set-ItemProperty -Path $edgeKey -Name WebAppInstallForceList -Value $json -Type String
        }
    }
}

function Set-ExtensionPolicy {
    [CmdletBinding(SupportsShouldProcess)]
    param([switch]$Remove)
    if ($extensions.Count -eq 0) {
        Write-Information 'No three.ws extension is on Edge Add-ons yet, so none is force-installed.' -InformationAction Continue
        return
    }
    $existing = @{}
    if (Test-Path $extKey) {
        $props = Get-ItemProperty -Path $extKey
        foreach ($p in $props.PSObject.Properties | Where-Object { $_.Name -match '^d+$' }) { $existing[$p.Name] = [string]$p.Value }
    }
    foreach ($entry in $extensions) {
        $name = ($existing.GetEnumerator() | Where-Object { $_.Value -eq $entry } | Select-Object -First 1).Key
        if ($Remove) {
            if ($name -and $PSCmdlet.ShouldProcess("$extKey\$name", 'Remove three.ws extension')) {
                Remove-ItemProperty -Path $extKey -Name $name
            }
        } elseif (-not $name) {
            $free = 1
            while ($existing.ContainsKey([string]$free)) { $free++ }
            if ($PSCmdlet.ShouldProcess("$extKey\$free", 'Add three.ws extension')) {
                if (-not (Test-Path $extKey)) { New-Item -Path $extKey -Force | Out-Null }
                Set-ItemProperty -Path $extKey -Name ([string]$free) -Value $entry -Type String
                $existing[[string]$free] = $entry
            }
        }
    }
}

Set-WebAppPolicy -Remove:$Remove
Set-ExtensionPolicy -Remove:$Remove
Write-Information 'Done. Open edge://policy and select Reload policies to confirm.' -InformationAction Continue

