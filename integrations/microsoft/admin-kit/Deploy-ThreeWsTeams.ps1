<#
.SYNOPSIS
Installs and pins three.ws in Microsoft Teams for an Entra group, through a Teams app setup policy.

.DESCRIPTION
Generated by scripts/microsoft-admin-kit.mjs. Do not edit by hand. Needs the MicrosoftTeams
PowerShell module and a Teams administrator account. It merges with an existing policy of the
same name, so apps already pinned in it stay. Use -WhatIf to see each change first, and
-Remove to roll the group assignment and the policy back.
Allow the app for your users first: Teams admin center > Teams apps > Manage apps >
three.ws > Publishing status, and the app permission policy that applies to the group.

.PARAMETER TeamsAppId
The three.ws Teams app id: the id of the app in Manage apps, which is the app id in the
manifest (the GUID Partner Center shows for the offer).

.PARAMETER GroupId
Object id of the Entra security group (or Microsoft 365 group) that receives the policy.

.PARAMETER PolicyName
Name of the app setup policy to create or update.

.PARAMETER Rank
Policy assignment rank within the group assignments. 1 is highest priority.

.EXAMPLE
./Deploy-ThreeWsTeams.ps1 -TeamsAppId 00000000-0000-0000-0000-000000000000 -GroupId 11111111-1111-1111-1111-111111111111 -WhatIf
#>
#Requires -Modules MicrosoftTeams
[CmdletBinding(SupportsShouldProcess)]
param(
    [Parameter(Mandatory)][guid]$TeamsAppId,
    [Parameter(Mandatory)][guid]$GroupId,
    [string]$PolicyName = 'three.ws',
    [ValidateRange(1, 1000)][int]$Rank = 1,
    [switch]$Remove
)

$ErrorActionPreference = 'Stop'
$appId = $TeamsAppId.ToString()

if (-not (Get-Command Get-CsTenant -ErrorAction SilentlyContinue) -or -not (Get-CsTenant -ErrorAction SilentlyContinue)) {
    Connect-MicrosoftTeams | Out-Null
}

$policy = Get-CsTeamsAppSetupPolicy -Identity $PolicyName -ErrorAction SilentlyContinue

if ($Remove) {
    if ($PSCmdlet.ShouldProcess($GroupId, "Remove the TeamsAppSetupPolicy assignment")) {
        Remove-CsGroupPolicyAssignment -GroupId $GroupId -PolicyType TeamsAppSetupPolicy -ErrorAction SilentlyContinue
    }
    if ($policy -and $PSCmdlet.ShouldProcess($PolicyName, 'Remove the app setup policy')) {
        Remove-CsTeamsAppSetupPolicy -Identity $PolicyName
    }
    return
}

$presetType = 'Microsoft.Teams.Policy.Administration.Cmdlets.Core.AppPreset'
$pinnedType = 'Microsoft.Teams.Policy.Administration.Cmdlets.Core.PinnedApp'

$presets = @()
$pinned = @()
if ($policy) {
    $presets = @($policy.AppPresetList | Where-Object { $_.Id -ne $appId })
    $pinned = @($policy.PinnedAppBarApps | Where-Object { $_.Id -ne $appId })
}
$presets += New-Object -TypeName $presetType -Property @{ Id = $appId }
$pinned += New-Object -TypeName $pinnedType -Property @{ Id = $appId; Order = $pinned.Count + 1 }

if ($policy) {
    if ($PSCmdlet.ShouldProcess($PolicyName, 'Update the app setup policy')) {
        Set-CsTeamsAppSetupPolicy -Identity $PolicyName -AppPresetList $presets -PinnedAppBarApps $pinned -AllowUserPinning $true
    }
} elseif ($PSCmdlet.ShouldProcess($PolicyName, 'Create the app setup policy')) {
    New-CsTeamsAppSetupPolicy -Identity $PolicyName -Description 'Installs and pins three.ws' -AppPresetList $presets -PinnedAppBarApps $pinned -AllowUserPinning $true | Out-Null
}

if ($PSCmdlet.ShouldProcess($GroupId, "Assign $PolicyName at rank $Rank")) {
    New-CsGroupPolicyAssignment -GroupId $GroupId -PolicyType TeamsAppSetupPolicy -PolicyName $PolicyName -Rank $Rank | Out-Null
    Write-Information 'Assigned. Teams applies group policy assignments within hours (up to 24).' -InformationAction Continue
}

