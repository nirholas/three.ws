// Pure generators for the IT admin deployment kit (integrations/microsoft/admin-kit/).
// Everything here takes data in and returns text out, so the CLI
// (scripts/microsoft-admin-kit.mjs) and the tests share one implementation and
// the output is byte-for-byte deterministic: no dates, no random values.
//
// Inputs are the real sources: the web app manifest from vite.config.js, the
// extension manifests under extensions/, and extensions/edge-store-ids.json.

import { runInNewContext } from 'node:vm';

export const EDGE_UPDATE_URL = 'https://edge.microsoft.com/extensionwebstorebase/v1/crx';
export const EDGE_POLICY_KEY = 'SOFTWARE\\Policies\\Microsoft\\Edge';
const EXTENSION_ID_RE = /^[a-p]{32}$/;

/**
 * The object literal of `manifest: { ... }` inside the VitePWA({ ... }) call.
 * The web app manifest is generated by vite-plugin-pwa at build time, so
 * vite.config.js is its only source. The block is plain literals; it is
 * evaluated in an empty vm context, so it cannot reach anything else.
 */
export function extractViteManifest(viteConfigSource) {
	const plugin = viteConfigSource.indexOf('VitePWA({');
	if (plugin < 0) throw new Error('vite.config.js has no VitePWA({ call');
	const key = viteConfigSource.indexOf('manifest: {', plugin);
	if (key < 0) throw new Error('the VitePWA config has no manifest: { block');
	const open = viteConfigSource.indexOf('{', key);
	let depth = 0;
	let i = open;
	while (i < viteConfigSource.length) {
		const ch = viteConfigSource[i];
		const next = viteConfigSource[i + 1];
		if (ch === '/' && next === '/') {
			i = viteConfigSource.indexOf('\n', i);
			if (i < 0) break;
			continue;
		}
		if (ch === '/' && next === '*') {
			i = viteConfigSource.indexOf('*/', i) + 2;
			continue;
		}
		if (ch === "'" || ch === '"' || ch === '`') {
			i++;
			while (viteConfigSource[i] !== ch) i += viteConfigSource[i] === '\\' ? 2 : 1;
		} else if (ch === '{') {
			depth++;
		} else if (ch === '}') {
			depth--;
			if (depth === 0) return runInNewContext(`(${viteConfigSource.slice(open, i + 1)})`, Object.create(null));
		}
		i++;
	}
	throw new Error('the VitePWA manifest block is not closed');
}

const sizeOf = (s) => String(s || '').split(/\s+/).map((p) => Number(p.split('x')[0])).filter(Boolean);

/**
 * What Edge needs to install the site as an app and keep its identity stable.
 * Returns problems as strings; an empty list means the manifest is ready.
 * `assetExists(src)` reports whether an icon file is served (public/ lookup).
 */
export function installReadiness(manifest, { assetExists = () => true } = {}) {
	const problems = [];
	if (!manifest.name && !manifest.short_name) problems.push('name or short_name is required');
	if (!manifest.id) problems.push('id is required so a policy-installed app keeps one identity');
	if (!manifest.start_url) problems.push('start_url is required');
	if (!manifest.scope) problems.push('scope is required');
	if (manifest.start_url && manifest.scope) {
		const base = 'https://example.invalid';
		const start = new URL(manifest.start_url, base);
		const scope = new URL(manifest.scope, base);
		if (!start.pathname.startsWith(scope.pathname)) problems.push('start_url is outside scope');
	}
	const displays = [manifest.display, ...(manifest.display_override || [])];
	if (!displays.some((d) => ['standalone', 'minimal-ui', 'fullscreen', 'window-controls-overlay'].includes(d))) {
		problems.push('display must open the app in its own window (standalone)');
	}
	const icons = manifest.icons || [];
	const png = (purpose, min) =>
		icons.some((i) => i.type === 'image/png' && (i.purpose || 'any').split(/\s+/).includes(purpose) && sizeOf(i.sizes).some((n) => n >= min));
	if (!png('any', 192)) problems.push('needs a PNG icon with purpose "any" at 192px or larger');
	if (!png('any', 512)) problems.push('needs a PNG icon with purpose "any" at 512px or larger');
	if (!png('maskable', 512)) problems.push('needs a maskable PNG icon at 512px or larger');
	for (const icon of icons) {
		if (!assetExists(icon.src)) problems.push(`icon ${icon.src} is not served from public/`);
	}
	return problems;
}

export function absoluteStartUrl(manifest, origin) {
	return new URL(manifest.start_url, origin).href;
}

/** Edge WebAppInstallForceList entries for the web app. */
export function webAppForceList(manifest, origin) {
	return [
		{
			url: absoluteStartUrl(manifest, origin),
			launch_container: 'window',
			create_desktop_shortcut: true,
			fallback_app_name: manifest.short_name || manifest.name,
		},
	];
}

/**
 * Split the extensions into the ones with an Edge Add-ons id (force-installable)
 * and the ones still waiting for store publication.
 * @param {{key:string,name:string,version:string}[]} extensions
 * @param {Record<string,string|null>} ids
 */
export function extensionForceList(extensions, ids) {
	const entries = [];
	const pending = [];
	for (const ext of extensions) {
		const id = ids[ext.key];
		if (id == null) {
			pending.push(ext);
			continue;
		}
		if (!EXTENSION_ID_RE.test(id)) throw new Error(`extensions/edge-store-ids.json: "${ext.key}" is not a 32 character Edge extension id`);
		entries.push({ ...ext, id, policy: `${id};${EDGE_UPDATE_URL}` });
	}
	return { entries, pending };
}

const crlf = (lines) => `${lines.join('\r\n')}\r\n`;
const regString = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

/** A .reg file that sets both Edge policies machine-wide. */
export function regFile({ webApps, extensionEntries }) {
	const lines = [
		'Windows Registry Editor Version 5.00',
		'',
		`[HKEY_LOCAL_MACHINE\\${EDGE_POLICY_KEY}]`,
		`"WebAppInstallForceList"="${regString(JSON.stringify(webApps))}"`,
	];
	if (extensionEntries.length) {
		lines.push('', `[HKEY_LOCAL_MACHINE\\${EDGE_POLICY_KEY}\\ExtensionInstallForcelist]`);
		extensionEntries.forEach((e, n) => lines.push(`"${n + 1}"="${regString(e.policy)}"`));
	}
	return crlf(lines);
}

/** The Chromium managed-policy JSON (Edge on macOS and Linux, and local testing). */
export function policyJson({ webApps, extensionEntries }) {
	const out = { WebAppInstallForceList: webApps };
	if (extensionEntries.length) out.ExtensionInstallForcelist = extensionEntries.map((e) => e.policy);
	return `${JSON.stringify(out, null, '\t')}\n`;
}

const psQuote = (s) => s.replace(/'/g, "''");

/** PowerShell that merges the policies into the registry, with -WhatIf and -Remove. */
export function edgePolicyScript({ webApps, extensionEntries }) {
	const apps = JSON.stringify(webApps);
	const exts = extensionEntries.map((e) => `'${psQuote(e.policy)}'`).join(', ');
	return crlf(`<#
.SYNOPSIS
Sets the three.ws Edge policies: installs the web app, and the extensions that are on Edge Add-ons.

.DESCRIPTION
Generated by scripts/microsoft-admin-kit.mjs. Do not edit by hand. It merges with the
policies already on the machine (it never replaces another entry) and -Remove takes out
only what this script added. Use -WhatIf to see every change without making it.
Run from an elevated prompt for -Scope Machine. Prefer Intune or Group Policy for fleets;
this script is for pilots, scripted images and non-managed devices.

.PARAMETER Scope
Machine writes HKLM (all users, needs elevation). User writes HKCU (the current user only).

.PARAMETER Remove
Rolls the policies back.

.EXAMPLE
./Set-ThreeWsEdgePolicy.ps1 -WhatIf

.EXAMPLE
./Set-ThreeWsEdgePolicy.ps1 -Scope Machine -Remove
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [ValidateSet('Machine', 'User')]
    [string]$Scope = 'Machine',
    [switch]$Remove
)

$ErrorActionPreference = 'Stop'
$hive = if ($Scope -eq 'Machine') { 'HKLM:' } else { 'HKCU:' }
$edgeKey = Join-Path $hive '${EDGE_POLICY_KEY}'
$extKey = Join-Path $edgeKey 'ExtensionInstallForcelist'

$webApps = @'
${apps}
'@ | ConvertFrom-Json
$extensions = @(${exts})

function Set-WebAppPolicy {
    [CmdletBinding(SupportsShouldProcess)]
    param([switch]$Remove)
    $current = @()
    if (Test-Path $edgeKey) {
        $raw = (Get-ItemProperty -Path $edgeKey -Name WebAppInstallForceList -ErrorAction SilentlyContinue).WebAppInstallForceList
        if ($raw) { $current = @($raw | ConvertFrom-Json) }
    }
    $ours = @($webApps.url)
    $kept = @($current | Where-Object { $ours -notcontains $_.url })
    $next = if ($Remove) { $kept } else { @($kept) + @($webApps) }
    if ($PSCmdlet.ShouldProcess("$edgeKey\\WebAppInstallForceList", $(if ($Remove) { 'Remove three.ws web app' } else { 'Add three.ws web app' }))) {
        if (-not (Test-Path $edgeKey)) { New-Item -Path $edgeKey -Force | Out-Null }
        if ($next.Count -eq 0) {
            Remove-ItemProperty -Path $edgeKey -Name WebAppInstallForceList -ErrorAction SilentlyContinue
        } else {
            $json = ConvertTo-Json -InputObject @($next) -Compress -Depth 5
            Set-ItemProperty -Path $edgeKey -Name WebAppInstallForceList -Value $json -Type String
        }
    }
}

function Set-ExtensionPolicy {
    [CmdletBinding(SupportsShouldProcess)]
    param([switch]$Remove)
    if ($extensions.Count -eq 0) {
        Write-Information 'No three.ws extension is on Edge Add-ons yet, so none is force-installed.' -InformationAction Continue
        return
    }
    $existing = @{}
    if (Test-Path $extKey) {
        $props = Get-ItemProperty -Path $extKey
        foreach ($p in $props.PSObject.Properties | Where-Object { $_.Name -match '^\d+$' }) { $existing[$p.Name] = [string]$p.Value }
    }
    foreach ($entry in $extensions) {
        $name = ($existing.GetEnumerator() | Where-Object { $_.Value -eq $entry } | Select-Object -First 1).Key
        if ($Remove) {
            if ($name -and $PSCmdlet.ShouldProcess("$extKey\\$name", 'Remove three.ws extension')) {
                Remove-ItemProperty -Path $extKey -Name $name
            }
        } elseif (-not $name) {
            $free = 1
            while ($existing.ContainsKey([string]$free)) { $free++ }
            if ($PSCmdlet.ShouldProcess("$extKey\\$free", 'Add three.ws extension')) {
                if (-not (Test-Path $extKey)) { New-Item -Path $extKey -Force | Out-Null }
                Set-ItemProperty -Path $extKey -Name ([string]$free) -Value $entry -Type String
                $existing[[string]$free] = $entry
            }
        }
    }
}

Set-WebAppPolicy -Remove:$Remove
Set-ExtensionPolicy -Remove:$Remove
Write-Information 'Done. Open edge://policy and select Reload policies to confirm.' -InformationAction Continue
`.split('\n'));
}

/** PowerShell that creates a Teams app setup policy and assigns it to a group. */
export function teamsScript({ policyName }) {
	return crlf(`<#
.SYNOPSIS
Installs and pins three.ws in Microsoft Teams for an Entra group, through a Teams app setup policy.

.DESCRIPTION
Generated by scripts/microsoft-admin-kit.mjs. Do not edit by hand. Needs the MicrosoftTeams
PowerShell module and a Teams administrator account. It merges with an existing policy of the
same name, so apps already pinned in it stay. Use -WhatIf to see each change first, and
-Remove to roll the group assignment and the policy back.
Allow the app for your users first: Teams admin center > Teams apps > Manage apps >
three.ws > Publishing status, and the app permission policy that applies to the group.

.PARAMETER TeamsAppId
The three.ws Teams app id: the id of the app in Manage apps, which is the app id in the
manifest (the GUID Partner Center shows for the offer).

.PARAMETER GroupId
Object id of the Entra security group (or Microsoft 365 group) that receives the policy.

.PARAMETER PolicyName
Name of the app setup policy to create or update.

.PARAMETER Rank
Policy assignment rank within the group assignments. 1 is highest priority.

.EXAMPLE
./Deploy-ThreeWsTeams.ps1 -TeamsAppId 00000000-0000-0000-0000-000000000000 -GroupId 11111111-1111-1111-1111-111111111111 -WhatIf
#>
#Requires -Modules MicrosoftTeams
[CmdletBinding(SupportsShouldProcess)]
param(
    [Parameter(Mandatory)][guid]$TeamsAppId,
    [Parameter(Mandatory)][guid]$GroupId,
    [string]$PolicyName = '${psQuote(policyName)}',
    [ValidateRange(1, 1000)][int]$Rank = 1,
    [switch]$Remove
)

$ErrorActionPreference = 'Stop'
$appId = $TeamsAppId.ToString()

if (-not (Get-Command Get-CsTenant -ErrorAction SilentlyContinue) -or -not (Get-CsTenant -ErrorAction SilentlyContinue)) {
    Connect-MicrosoftTeams | Out-Null
}

$policy = Get-CsTeamsAppSetupPolicy -Identity $PolicyName -ErrorAction SilentlyContinue

if ($Remove) {
    if ($PSCmdlet.ShouldProcess($GroupId, "Remove the TeamsAppSetupPolicy assignment")) {
        Remove-CsGroupPolicyAssignment -GroupId $GroupId -PolicyType TeamsAppSetupPolicy -ErrorAction SilentlyContinue
    }
    if ($policy -and $PSCmdlet.ShouldProcess($PolicyName, 'Remove the app setup policy')) {
        Remove-CsTeamsAppSetupPolicy -Identity $PolicyName
    }
    return
}

$presetType = 'Microsoft.Teams.Policy.Administration.Cmdlets.Core.AppPreset'
$pinnedType = 'Microsoft.Teams.Policy.Administration.Cmdlets.Core.PinnedApp'

$presets = @()
$pinned = @()
if ($policy) {
    $presets = @($policy.AppPresetList | Where-Object { $_.Id -ne $appId })
    $pinned = @($policy.PinnedAppBarApps | Where-Object { $_.Id -ne $appId })
}
$presets += New-Object -TypeName $presetType -Property @{ Id = $appId }
$pinned += New-Object -TypeName $pinnedType -Property @{ Id = $appId; Order = $pinned.Count + 1 }

if ($policy) {
    if ($PSCmdlet.ShouldProcess($PolicyName, 'Update the app setup policy')) {
        Set-CsTeamsAppSetupPolicy -Identity $PolicyName -AppPresetList $presets -PinnedAppBarApps $pinned -AllowUserPinning $true
    }
} elseif ($PSCmdlet.ShouldProcess($PolicyName, 'Create the app setup policy')) {
    New-CsTeamsAppSetupPolicy -Identity $PolicyName -Description 'Installs and pins three.ws' -AppPresetList $presets -PinnedAppBarApps $pinned -AllowUserPinning $true | Out-Null
}

if ($PSCmdlet.ShouldProcess($GroupId, "Assign $PolicyName at rank $Rank")) {
    New-CsGroupPolicyAssignment -GroupId $GroupId -PolicyType TeamsAppSetupPolicy -PolicyName $PolicyName -Rank $Rank | Out-Null
    Write-Information 'Assigned. Teams applies group policy assignments within hours (up to 24).' -InformationAction Continue
}
`.split('\n'));
}
