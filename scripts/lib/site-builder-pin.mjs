// Generates the one pinned <agent-3d> release constant each site-builder embed
// (WordPress, Framer, Webflow) loads from, so `npm run build:site-builder-embeds`
// after a new `npm run release:lib` updates every embed in one pass. The ledger
// (data/agent-3d-releases.json) stays the single source of truth; nothing here
// hardcodes a version or a hash.

import { releasedVersions } from './agent-3d-releases.mjs';

const WARN = 'Generated by scripts/build-site-builder-embeds.mjs from data/agent-3d-releases.json. Do not edit by hand: run `npm run build:site-builder-embeds`.';

/** The newest released version plus its file hashes and CDN URLs. */
export function latestPin(ledger) {
	const versions = releasedVersions(ledger);
	const version = versions[versions.length - 1];
	if (!version) throw new Error('data/agent-3d-releases.json has no releases');
	const integrity = ledger.releases[version].integrity;
	const base = `https://three.ws/agent-3d/${version}`;
	return {
		version,
		jsUrl: `${base}/agent-3d.js`,
		jsIntegrity: integrity['agent-3d.js'],
		umdUrl: `${base}/agent-3d.umd.cjs`,
		umdIntegrity: integrity['agent-3d.umd.cjs'],
	};
}

export function renderPhp(pin) {
	return `<?php
/**
 * ${WARN}
 *
 * @package ThreeWsAgent
 */

if (!defined('ABSPATH')) {
	exit;
}

define('THREE_WS_AGENT3D_VERSION', '${pin.version}');
define('THREE_WS_AGENT3D_JS_URL', '${pin.jsUrl}');
define('THREE_WS_AGENT3D_JS_INTEGRITY', '${pin.jsIntegrity}');
define('THREE_WS_AGENT3D_UMD_URL', '${pin.umdUrl}');
define('THREE_WS_AGENT3D_UMD_INTEGRITY', '${pin.umdIntegrity}');
`;
}

export function renderTs(pin) {
	return `// ${WARN}

export const AGENT3D_VERSION = '${pin.version}';
export const AGENT3D_JS_URL = '${pin.jsUrl}';
export const AGENT3D_JS_INTEGRITY = '${pin.jsIntegrity}';
export const AGENT3D_UMD_URL = '${pin.umdUrl}';
export const AGENT3D_UMD_INTEGRITY = '${pin.umdIntegrity}';
`;
}

export const GENERATED_FILES = [
	{ path: 'integrations/wordpress/three-ws-agent/includes/pinned-release.php', render: renderPhp },
	{ path: 'integrations/framer/src/pinned-release.ts', render: renderTs },
	{ path: 'integrations/webflow/src/pinned-release.ts', render: renderTs },
];
