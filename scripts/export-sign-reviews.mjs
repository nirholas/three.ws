#!/usr/bin/env node
// Export the review workspace (sign_reviews in the database) into a pack's
// committed review ledger, src/sign-packs/reviews/<id>.js.
//
// Serving reads only the committed ledger, so this is the one step that can
// put a reviewed sign live, and it lands as an ordinary diff a maintainer reads
// before committing. Only verdicts by reviewers whose grant is still active and
// only verdicts on each sign's CURRENT content are exported: a verdict on an
// older version of a sign is history, not an approval.
//
//   node --env-file=.env.local scripts/export-sign-reviews.mjs <pack>
//   npm run sign:export-reviews -- <pack> [--check]
//
// --check writes nothing and exits 1 when the committed ledger is out of date.
// Exit codes: 0 done (or up to date), 1 out of date under --check, 2 usage or
// unknown pack, 3 no database configured.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const packArg = args.find((a) => !a.startsWith('--'));

if (!packArg) {
	console.error('usage: export-sign-reviews <pack id> [--check]');
	process.exit(2);
}
if (!process.env.DATABASE_URL) {
	console.error('DATABASE_URL is not set. Run with: node --env-file=.env.local scripts/export-sign-reviews.mjs ' + packArg);
	process.exit(3);
}

const { getReviewPack, reviewRows } = await import('../api/_lib/sign-review.js');
const { signContentHash } = await import('../src/sign-packs/hash.js');
const { packReview } = await import('../src/sign-packs/review.js');

const pack = getReviewPack(packArg);
if (!pack) {
	console.error(`no pack under review is called "${packArg}" (native packs need no ledger)`);
	process.exit(2);
}

const current = Object.fromEntries(Object.entries(pack.signs).map(([k, s]) => [k, signContentHash(s)]));
const rows = (await reviewRows(pack.id))
	.filter((r) => current[r.sign_key] === r.content_hash)
	.map((r) => ({
		sign: r.sign_key,
		hash: r.content_hash,
		reviewer: String(r.reviewer_id),
		name: r.display_name,
		verdict: r.verdict,
	}))
	.sort((a, b) => a.sign.localeCompare(b.sign) || a.reviewer.localeCompare(b.reviewer));

const review = packReview(pack, rows);
const body = `// Committed review ledger for ${pack.name} (${pack.id}).
// Generated by scripts/export-sign-reviews.mjs from the review workspace. Do not
// edit by hand: a sign is served only when this ledger holds ${pack.requiredApprovals} approvals from
// distinct reviewers on its current content hash (src/sign-packs/review.js).
// ${review.approved.length} of ${review.total} signs approved.

export default Object.freeze(${JSON.stringify(rows, null, '\t')});
`;

const file = path.join(root, 'src/sign-packs/reviews', `${pack.id}.js`);
const before = await readFile(file, 'utf8').catch(() => null);
if (before === body) {
	console.log(`${pack.id}: ledger is up to date (${review.approved.length} of ${review.total} approved)`);
	process.exit(0);
}
if (check) {
	console.error(`${pack.id}: ledger is out of date; run npm run sign:export-reviews -- ${pack.id}`);
	process.exit(1);
}
await mkdir(path.dirname(file), { recursive: true });
await writeFile(file, body);
console.log(`${pack.id}: wrote ${path.relative(root, file)} with ${rows.length} verdicts (${review.approved.length} of ${review.total} approved)`);
console.log(`Import it as the pack's reviews: import REVIEWS from './reviews/${pack.id}.js'; then reviews: REVIEWS.`);
process.exit(0);
