#!/usr/bin/env node
// Writes the Power Query (M) scripts in integrations/microsoft/power-bi-usage/queries/
// from the usage feed's entity model (api/_lib/odata/usage-model.js), so the
// typed column lists can never drift from what the OData feed serves.
//
//   node scripts/build-power-bi-usage-queries.mjs          write the files
//   node scripts/build-power-bi-usage-queries.mjs --check  exit 1 when a file is stale
//
// tests/power-bi-usage-queries.test.js runs the same comparison under npm test.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ENTITY_SETS } from '../api/_lib/odata/usage-model.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const QUERY_DIR = join(ROOT, 'integrations/microsoft/power-bi-usage/queries');
export const DEFAULT_FEED_URL = 'https://three.ws/api/odata/v1/';

// Edm type to the M type Power BI should hold the column as. Edm.Decimal maps
// to plain number rather than Currency.Type, because Currency rounds to four
// decimals and the feed carries six.
const M_TYPES = {
	'Edm.String': 'type text',
	'Edm.Date': 'type date',
	'Edm.DateTimeOffset': 'type datetimezone',
	'Edm.Int32': 'Int64.Type',
	'Edm.Int64': 'Int64.Type',
	'Edm.Double': 'type number',
	'Edm.Decimal': 'type number',
	'Edm.Boolean': 'type logical',
};

function mType(edm) {
	const t = M_TYPES[edm];
	if (!t) throw new Error(`no Power Query type mapping for ${edm}; add one to M_TYPES`);
	return t;
}

const HEADER = '// Generated by scripts/build-power-bi-usage-queries.mjs from api/_lib/odata/usage-model.js.\n// Regenerate after a model change; do not edit by hand.\n';

export function feedUrlQuery() {
	return `${HEADER}// Power Query parameter: the three.ws usage feed root. Name this query FeedUrl.
"${DEFAULT_FEED_URL}" meta [IsParameterQuery = true, Type = "Text", IsParameterQueryRequired = true]
`;
}

export function entityQuery(set) {
	const cols = Object.entries(set.props).map(([name, p]) => `        {"${name}", ${mType(p.type)}}`);
	return `${HEADER}// ${set.description}
// Name this query ${set.name}. It reads the FeedUrl parameter.
let
    Source = OData.Feed(FeedUrl, null, [Implementation = "2.0"]),
    Rows = Source{[Name = "${set.name}", Signature = "table"]}[Data],
    Columns = Table.SelectColumns(Rows, {${Object.keys(set.props).map((n) => `"${n}"`).join(', ')}}),
    Typed = Table.TransformColumnTypes(Columns, {
${cols.join(',\n')}
    })
in
    Typed
`;
}

/** Every generated file as [relative name, contents]. */
export function queryFiles() {
	return [['FeedUrl.pq', feedUrlQuery()], ...ENTITY_SETS.map((s) => [`${s.name}.pq`, entityQuery(s)])];
}

function main() {
	const check = process.argv.includes('--check');
	mkdirSync(QUERY_DIR, { recursive: true });
	let stale = 0;
	for (const [name, text] of queryFiles()) {
		const file = join(QUERY_DIR, name);
		const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
		if (current === text) continue;
		if (check) {
			stale++;
			console.error(`stale: ${file}`);
		} else {
			writeFileSync(file, text);
			console.log(`wrote ${file}`);
		}
	}
	if (check && stale) {
		console.error('run node scripts/build-power-bi-usage-queries.mjs');
		process.exit(1);
	}
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
