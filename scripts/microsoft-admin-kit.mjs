// Regenerates integrations/microsoft/admin-kit/ from the real sources:
// the web app manifest (vite.config.js), the extension manifests and
// extensions/edge-store-ids.json.
//
//   node scripts/microsoft-admin-kit.mjs           write the kit
//   node scripts/microsoft-admin-kit.mjs --check   fail if the committed kit is stale
//
// Deterministic: running it twice leaves no diff. Nothing tenant-specific is
// baked in: the Teams app id and group id are parameters of the PowerShell.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
	EDGE_UPDATE_URL,
	extractViteManifest,
	installReadiness,
	webAppForceList,
	extensionForceList,
	regFile,
	policyJson,
	edgePolicyScript,
	teamsScript,
} from './lib/microsoft-admin-kit.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'integrations', 'microsoft', 'admin-kit');
export const ORIGIN = 'https://three.ws';
const EXTENSIONS = [
	{ key: 'walk-avatar', dir: 'extensions/walk-avatar' },
	{ key: 'checkout-companion', dir: 'extensions/checkout-companion' },
];

const readJson = (rel) => JSON.parse(readFileSync(join(root, rel), 'utf8'));

export function loadInputs() {
	const manifest = extractViteManifest(readFileSync(join(root, 'vite.config.js'), 'utf8'));
	const extensions = EXTENSIONS.map(({ key, dir }) => {
		const m = readJson(`${dir}/manifest.json`);
		return { key, name: m.name, version: m.version };
	});
	const ids = readJson('extensions/edge-store-ids.json');
	return { manifest, extensions, ids };
}

const table = (rows) => rows.map((r) => `| ${r.join(' | ')} |`).join('\n');

function intuneDoc({ webApps, entries, pending }) {
	const appJson = JSON.stringify(webApps, null, 2);
	const extRows = entries.length
		? entries.map((e) => `| ${e.name} | \`${e.policy}\` |`).join('\n')
		: '| (none published yet) | |';
	return `# Intune settings catalog: three.ws

Generated by scripts/microsoft-admin-kit.mjs. Do not edit by hand.

Intune admin center > Devices > Configuration > Create > New policy > Windows 10 and later > Settings catalog. Add the settings below in the Microsoft Edge category, assign the policy to a device group, and save.

## Install the web app

Setting: **Configure list of force-installed Web Apps** (policy \`WebAppInstallForceList\`). Set it to Enabled, with this value:

\`\`\`json
${appJson}
\`\`\`

Entries use \`url\` (the start page that links the manifest), \`launch_container\` (\`window\` opens it as an app), \`create_desktop_shortcut\` and \`fallback_app_name\`.

## Install the extensions

Setting: **Control which extensions are installed silently** (policy \`ExtensionInstallForcelist\`). Set it to Enabled and add one entry per extension, in the form \`<extension id>;<update url>\`. The update URL for Edge Add-ons is \`${EDGE_UPDATE_URL}\`.

| Extension | Entry |
| --- | --- |
${extRows}
${pending.length ? `\nNot on Edge Add-ons yet, so not in the list: ${pending.map((p) => p.name).join(', ')}. Once published, put the id in extensions/edge-store-ids.json and run \`node scripts/microsoft-admin-kit.mjs\`.\n` : ''}
## Verify on a device

Open \`edge://policy\`, select **Reload policies**, and check that both policies show status OK. The app appears in \`edge://apps\`, and the extensions in \`edge://extensions\` marked "Installed by your organization".
`;
}

function readme({ manifest, entries, pending, extensions }) {
	const extRows = extensions.map((e) => {
		const published = entries.find((x) => x.key === e.key);
		return [e.name, e.version, published ? `\`${published.id}\`` : 'pending Edge Add-ons publication'];
	});
	return `# three.ws IT admin deployment kit

Generated by scripts/microsoft-admin-kit.mjs. Do not edit by hand. Regenerate with \`node scripts/microsoft-admin-kit.mjs\`; \`--check\` fails when this folder is stale.

The full guide, with a decision table, rollback and FAQ, is [docs/microsoft-admin-deployment.md](../../../docs/microsoft-admin-deployment.md).

## What is here

| File | Use |
| --- | --- |
| edge-policies.json | The two Edge policies as a managed-policy JSON file (Edge on macOS and Linux, and local testing) |
| three-ws-edge-policies.reg | The same policies as a registry import, for machines not managed by Intune or Group Policy |
| intune-settings-catalog.md | The exact Intune settings catalog settings and values |
| Set-ThreeWsEdgePolicy.ps1 | Merges the policies into the registry. Supports -WhatIf and -Remove |
| Deploy-ThreeWsTeams.ps1 | Creates a Teams app setup policy that installs and pins three.ws for a group. Supports -WhatIf and -Remove |

## Source of the values

| Value | Source |
| --- | --- |
| Web app URL | \`start_url\` of the web app manifest: ${new URL(manifest.start_url, ORIGIN).href} |
| Web app identity | manifest \`id\`: \`${manifest.id}\` |
| Extension update URL | ${EDGE_UPDATE_URL} |

${table([['Extension', 'Version', 'Edge Add-ons id'], ['---', '---', '---'], ...extRows])}
${pending.length ? `\nExtensions marked pending have no Edge Add-ons id yet, so they are not force-installed. Either wait for publication, or self-host: build the package (\`npm run package:edge\`), host a signed CRX and an update manifest XML on your own HTTPS server, and use \`<extension id>;<your update manifest URL>\` in the same policy.\n` : ''}
## Group Policy (ADMX) without Intune

1. Download the Microsoft Edge policy templates (ADMX) from https://www.microsoft.com/edge/business/download and copy \`msedge.admx\` and its \`en-US\\msedge.adml\` into the domain PolicyDefinitions store.
2. Group Policy Management Editor > Computer Configuration > Administrative Templates > Microsoft Edge > Applications > **Configure list of force-installed Web Apps**: Enabled, paste the JSON from intune-settings-catalog.md.
3. Computer Configuration > Administrative Templates > Microsoft Edge > Extensions > **Control which extensions are installed silently**: Enabled, then Show, one entry per line.
4. Run \`gpupdate /force\` on a test machine, then check \`edge://policy\`.
`;
}

/** Every file of the kit as { relative path: text }. */
export function buildKit(inputs = loadInputs()) {
	const { manifest, extensions, ids } = inputs;
	const problems = installReadiness(manifest, { assetExists: (src) => existsSync(join(root, 'public', src.replace(/^\//, ''))) });
	if (problems.length) throw new Error(`web app manifest is not ready for force install:\n- ${problems.join('\n- ')}`);
	const webApps = webAppForceList(manifest, ORIGIN);
	const { entries, pending } = extensionForceList(extensions, ids);
	const data = { webApps, extensionEntries: entries };
	return {
		'README.md': readme({ manifest, entries, pending, extensions }),
		'edge-policies.json': policyJson(data),
		'three-ws-edge-policies.reg': regFile(data),
		'intune-settings-catalog.md': intuneDoc({ webApps, entries, pending }),
		'Set-ThreeWsEdgePolicy.ps1': edgePolicyScript(data),
		'Deploy-ThreeWsTeams.ps1': teamsScript({ policyName: 'three.ws' }),
	};
}

function main(argv) {
	const kit = buildKit();
	if (argv.includes('--check')) {
		const stale = Object.entries(kit).filter(([name, text]) => {
			const file = join(outDir, name);
			return !existsSync(file) || readFileSync(file, 'utf8') !== text;
		});
		if (stale.length) {
			console.error(`admin kit is stale: ${stale.map(([n]) => n).join(', ')}. Run node scripts/microsoft-admin-kit.mjs`);
			return 1;
		}
		console.log('admin kit is up to date');
		return 0;
	}
	mkdirSync(outDir, { recursive: true });
	for (const [name, text] of Object.entries(kit)) writeFileSync(join(outDir, name), text);
	console.log(`wrote ${Object.keys(kit).length} files to integrations/microsoft/admin-kit/`);
	return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exit(main(process.argv.slice(2)));
